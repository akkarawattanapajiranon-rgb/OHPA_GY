export function getRtrShutdownHoursForDate(dateStr?: string, customData?: Record<string, RtrShutdownEntry>): RtrShutdownEntry {
  const dataSource = customData || DEFAULT_RTR_SHUTDOWN_DATA;
  if (!dateStr || !dataSource) return {};
  const clean = String(dateStr).replace(/^[📅📄\s]*วันที่\s*/, "").trim();
  if (dataSource[clean]) return dataSource[clean];

  const parts = clean.split(/[/.-]/);
  if (parts.length === 3) {
    let d = "01", m = "09", y = "2026";
    if (parts[0].length === 4) {
      y = parts[0];
      m = parts[1].padStart(2, "0");
      d = parts[2].padStart(2, "0");
    } else {
      d = parts[0].padStart(2, "0");
      m = parts[1].padStart(2, "0");
      y = parts[2].length === 4 ? parts[2] : (parseInt(parts[2], 10) > 2400 ? String(parseInt(parts[2], 10) - 543) : "2026");
    }
    const k = `${d}/${m}/${y}`;
    if (dataSource[k]) return dataSource[k];
    const kShort = `${parseInt(d, 10)}/${parseInt(m, 10)}/${y}`;
    if (dataSource[kShort]) return dataSource[kShort];
    const kIso = `${y}-${m}-${d}`;
    if (dataSource[kIso]) return dataSource[kIso];
  }
  return {};
}
